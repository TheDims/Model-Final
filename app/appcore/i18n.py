def t(key, lang="en", **kw):
    """Vertaalde tekst; valt terug op Engels als er geen vertaling is."""
    row = T.get(key)
    if row is None:
        return key
    s = row[_ORDER.index(lang)] if lang in _ORDER else row[0]
    return s.format(**kw) if kw else s


def date_long(ts, lang):
    """Bv. 'Wednesday 14 October', 'woensdag 14 oktober', '10월 14일 수요일'."""
    wd, d, mo = DAYS[lang][ts.weekday()], ts.day, MONTHS[lang][ts.month - 1]
    if lang == "ko":
        return f"{mo} {d}일 {wd}"
    if lang == "pt":
        return f"{wd}, {d} de {mo}"
    if lang == "hi":
        return f"{wd}, {d} {mo}"
    return f"{wd} {d} {mo}"


def date_short(ts, lang):
    """Voor grafieklabels: bv. 'Wed 14 Oct', 'wo 14 okt', '10/14 (수)'."""
    wd, d = DAYS[lang][ts.weekday()], ts.day
    if lang == "ko":
        return f"{ts.month}/{d} ({wd[0]})"
    if lang == "hi":
        return f"{wd} {d}"
    return f"{wd[:3]} {d} {MONTHS[lang][ts.month - 1][:3]}"


def weekday_short(ts, lang):
    """Bv. 'Sat', 'za', '토', 'lör', 'sáb', 'शनि'."""
    if lang == "hi":
        return ["सोम", "मंगल", "बुध", "गुरु", "शुक्र", "शनि", "रवि"][ts.weekday()]
    wd = DAYS[lang][ts.weekday()]
    return wd[0] if lang == "ko" else wd[:3].capitalize()


def day_month(ts, lang):
    """Bv. '27 Sep', '9월 27일'."""
    return f"{MONTHS[lang][ts.month - 1]} {ts.day}일" if lang == "ko" else f"{ts.day} {MONTHS[lang][ts.month - 1][:3]}"


def month_short(ts, lang):
    """Bv. 'Oct', '10월'."""
    return MONTHS[lang][ts.month - 1] if lang == "ko" else MONTHS[lang][ts.month - 1][:3].capitalize()


def time_str(ts, lang):
    """India en Engels: 12-uursklok (11:15 AM); andere talen 24-uurs (11:15)."""
    return ts.strftime("%I:%M %p").lstrip("0") if lang in ("en", "hi") else ts.strftime("%H:%M")
